"""Insert the draft commentary into PowerPoint and Word outputs.

Both functions take an object the existing builders already hold (a
python-pptx Presentation or a python-docx Document), so wiring them in is one
call in each builder. Every inserted section carries the heading
"Draft commentary, engineer review required".
"""

from __future__ import annotations

from .commentary import UNVERIFIED, Commentary

HEADING = "Draft commentary, engineer review required"


def _criteria_lines(c: Commentary) -> list[str]:
    return [f"{cc.criterion}: {cc.comment}" for cc in c.criteria_commentary]


def _anomaly_lines(c: Commentary) -> list[str]:
    lines = [f"{a.anomaly_id} ({a.confidence} confidence): {a.likely_cause} "
             f"Evidence: {a.evidence} Check: {a.suggested_check}" for a in c.anomaly_explanations]
    lines += [f"[{UNVERIFIED.capitalize()}] {m.channel}: {m.description} {m.reason}"
              for m in c.model_suggested_anomalies]
    return lines


def add_draft_section_docx(doc, c: Commentary, level: int = 1) -> None:
    """Append the draft section to a python-docx Document."""
    from docx.shared import RGBColor

    doc.add_heading(HEADING, level=level)
    warn = doc.add_paragraph().add_run(
        "Generated by an AI model from the computed test summary. Every number has been "
        "checked against the summary; wording and interpretation have not. Review before issue.")
    warn.italic = True
    warn.font.color.rgb = RGBColor(0xC0, 0x00, 0x00)

    doc.add_heading("Results", level=level + 1)
    for p in c.results_commentary:
        doc.add_paragraph(p)
    doc.add_heading("Criteria", level=level + 1)
    for line in _criteria_lines(c):
        doc.add_paragraph(line, style="List Bullet")
    if c.anomaly_explanations or c.model_suggested_anomalies:
        doc.add_heading("Anomalies", level=level + 1)
        for line in _anomaly_lines(c):
            doc.add_paragraph(line, style="List Bullet")


def add_draft_slides_pptx(prs, c: Commentary, layout_index: int = 5) -> None:
    """Append draft slides to a python-pptx Presentation.

    layout_index 5 is "Title Only" in the default template; set it to the
    matching layout in the MIRA template.
    """
    from pptx.util import Pt

    def slide(title: str, paragraphs: list[str], size: int):
        s = prs.slides.add_slide(prs.slide_layouts[layout_index])
        s.shapes.title.text = f"{HEADING}: {title}"
        box = s.shapes.add_textbox(Pt(36), Pt(110), prs.slide_width - Pt(72), prs.slide_height - Pt(140))
        tf = box.text_frame
        tf.word_wrap = True
        for i, text in enumerate(paragraphs):
            para = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            para.text = text
            para.font.size = Pt(size)
            para.space_after = Pt(6)

    slide("results", c.results_commentary, 12)
    slide("criteria", _criteria_lines(c), 12)
    if c.anomaly_explanations or c.model_suggested_anomalies:
        slide("anomalies", _anomaly_lines(c), 11)
